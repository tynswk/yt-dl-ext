# yt-dl-ext の Native Messaging ホストを Chrome / Edge に登録する。管理者権限は不要。
# 使い方:  powershell -ExecutionPolicy Bypass -File install-nativehost.ps1
#          （拡張IDを自動検出できない場合は -ExtensionId <ID> を付ける）
#
# ホストの実体は %LOCALAPPDATA%\yt-dl-ext\host へコピーして、そこを登録する。
# 同期フォルダ（Google Drive / OneDrive など）を直接登録しないのは、
#   ・同期が止まっていたり未マウントだと Chrome がホストを起動できない
#   ・初回アクセスで実体のダウンロードが走り、起動が数秒遅れることがある
# ため。ローカルの ASCII パスに置くのが確実。
param([string]$ExtensionId)

$ErrorActionPreference = 'Stop'

$root     = Split-Path -Parent $MyInvocation.MyCommand.Path
$extDir   = Join-Path $root 'extension'
$srcHost  = Join-Path $root 'host\native_host.py'
$hostName = 'com.ytdlext.host'

$installDir = Join-Path $env:LOCALAPPDATA 'yt-dl-ext\host'
$dstHost    = Join-Path $installDir 'native_host.py'
$launcher   = Join-Path $installDir 'run_host.bat'
$manifest   = Join-Path $installDir "$hostName.json"

if (-not (Test-Path $srcHost)) { throw "native_host.py が見つからない: $srcHost" }

# --- python.exe の絶対パスを確定させる ------------------------------------
# PATH に頼ると、Chrome が継承した環境に python が無い場合に無言で失敗する。
$python = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $python) { $python = (Get-Command py -ErrorAction SilentlyContinue).Source }
if (-not $python) { throw 'python.exe が見つからない。Python をインストールして PATH を通してください。' }
Write-Host "python : $python"

# --- 拡張ID を決める -------------------------------------------------------
if (-not $ExtensionId) {
    $target = (Resolve-Path $extDir).Path.TrimEnd('\')

    # デベロッパーモードで読み込んだ拡張は 'Secure Preferences' 側に記録される。
    # 'Preferences' だけを見ると見つからないので両方を探す。
    $browsers = @(
        "$env:LOCALAPPDATA\Google\Chrome\User Data",
        "$env:LOCALAPPDATA\Microsoft\Edge\User Data",
        "$env:LOCALAPPDATA\Chromium\User Data"
    ) | Where-Object { Test-Path $_ }

    $prefs = foreach ($b in $browsers) {
        Get-ChildItem $b -Directory -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -eq 'Default' -or $_.Name -like 'Profile *' } |
            ForEach-Object {
                foreach ($f in 'Secure Preferences', 'Preferences') {
                    $candidate = Join-Path $_.FullName $f
                    if (Test-Path $candidate) { $candidate }
                }
            }
    }

    foreach ($p in $prefs) {
        $settings = (Get-Content $p -Raw -Encoding UTF8 | ConvertFrom-Json).extensions.settings
        if (-not $settings) { continue }
        foreach ($prop in $settings.PSObject.Properties) {
            $path = $prop.Value.path
            if ($path -and $path.TrimEnd('\') -ieq $target) {
                $ExtensionId = $prop.Name
                Write-Host "拡張ID: $ExtensionId （自動検出）"
                break
            }
        }
        if ($ExtensionId) { break }
    }
}

if (-not $ExtensionId) {
    Write-Host ''
    Write-Host '拡張IDを自動検出できなかった。先に chrome://extensions で' -ForegroundColor Yellow
    Write-Host '「パッケージ化されていない拡張機能を読み込む」から次を読み込んでください:' -ForegroundColor Yellow
    Write-Host "  $extDir"
    Write-Host 'カードに表示される ID を貼り付けてください。'
    $ExtensionId = (Read-Host '拡張ID').Trim()
}

if ($ExtensionId -notmatch '^[a-p]{32}$') { throw "拡張IDの形式が不正: $ExtensionId" }

# --- ホストをローカルへ配置 ------------------------------------------------
New-Item -ItemType Directory -Force -Path $installDir | Out-Null
Copy-Item $srcHost $dstHost -Force

# 起動用バッチ。python の絶対パスを埋め込むので PATH に依存しない。
# ASCII のみ（cmd.exe は .bat を ANSI で読むため日本語コメントは壊れる）。
@"
@echo off
rem Generated by install-nativehost.ps1 -- do not edit by hand.
"$python" -u "$dstHost"
"@ | ForEach-Object { [System.IO.File]::WriteAllText($launcher, $_, (New-Object System.Text.ASCIIEncoding)) }

# --- ホストマニフェスト ----------------------------------------------------
$json = [ordered]@{
    name           = $hostName
    description    = 'yt-dl-ext native host'
    path           = $launcher
    type           = 'stdio'
    allowed_origins = @("chrome-extension://$ExtensionId/")
} | ConvertTo-Json

# BOM を付けてはいけない。Set-Content -Encoding UTF8 は PowerShell 5.1 では BOM 付きになり、
# Chrome がマニフェストを読めず「ホストに接続できない」になる。
[System.IO.File]::WriteAllText($manifest, $json, (New-Object System.Text.UTF8Encoding $false))

Write-Host "配置先 : $installDir"

# --- レジストリに登録（HKCU なので管理者権限不要）--------------------------
foreach ($browser in 'Google\Chrome', 'Microsoft\Edge') {
    $key = "HKCU:\Software\$browser\NativeMessagingHosts\$hostName"
    New-Item -Path $key -Force | Out-Null
    Set-ItemProperty -Path $key -Name '(default)' -Value $manifest
    Write-Host "登録   : $key"
}

# --- 登録した経路で実際に起動できるか検証 ----------------------------------
Write-Host ''
Write-Host '登録した経路でホストを起動して疎通確認…'
$logPath = Join-Path $installDir 'debug.log'
Remove-Item $logPath -Force -ErrorAction SilentlyContinue

# stdout を同期 Read で待つと（応答が無いとき）永久にブロックするので、
# 起動ログの出現をポーリングして判定する。ホストは環境変数なしでも
# 起動時に1行だけ debug.log に残す。
$proc = Start-Process "$env:SystemRoot\System32\cmd.exe" -ArgumentList "/c `"$launcher`"" `
        -WindowStyle Hidden -PassThru

$ok = $false
$deadline = (Get-Date).AddSeconds(20)
while ((Get-Date) -lt $deadline) {
    if ((Test-Path $logPath) -and (Select-String -Path $logPath -Pattern 'host start' -Quiet)) {
        $ok = $true; break
    }
    Start-Sleep -Milliseconds 300
}

if ($ok) {
    $line = (Get-Content $logPath | Select-Object -First 1)
    Write-Host "疎通OK : $line" -ForegroundColor Green
    if ($line -notmatch 'ytdlp= True')  { Write-Warning 'yt-dlp が見つかりません: pip install -U yt-dlp' }
    if ($line -notmatch 'ffmpeg= True') { Write-Warning 'ffmpeg が見つかりません（mp4結合と音声変換に必要）' }
} else {
    Write-Warning "ホストを起動できませんでした。手動で確認してください:"
    Write-Host "  cmd /c `"$launcher`""
}
try { Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue } catch {}
Get-CimInstance Win32_Process -Filter "Name='python.exe'" |
    Where-Object { $_.CommandLine -like '*yt-dl-ext*native_host*' } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }

Write-Host ''
Write-Host 'Chrome を完全に終了してから起動し直してください。' -ForegroundColor Green
